function haversineM(lat1, lng1, lat2, lng2) {
  const R = 6371000;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLng = ((lng2 - lng1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLng / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

export function nearestStation(lat, lng) {
  if (!lat || !lng) return null;
  let best = null;
  let bestDist = Infinity;
  for (const [name, line, sLat, sLng] of STATIONS) {
    const d = haversineM(lat, lng, sLat, sLng);
    if (d < bestDist) {
      bestDist = d;
      best = { name, line };
    }
  }
  if (!best) return null;
  const walkMin = Math.max(1, Math.round((bestDist * 1.3) / 80));
  return { ...best, walkMin, distM: Math.round(bestDist) };
}
